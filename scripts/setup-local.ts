/**
 * One-command local setup against `supabase start`:
 *   npm run local:setup              # backend + simulator (127.0.0.1)
 *   npm run local:setup -- --host 192.168.1.20   # reachable from an iPhone on the LAN
 *   npm run local:setup -- --port 3200           # API port (default 3100)
 *
 * Writes .env from `supabase status`, creates the demo users, and prints the
 * matching Config/Secrets.xcconfig for the iOS app.
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { DEMO_USERS, ensureDemoUsers } from './demo-users.js';

async function main() {
  const arg = (name: string, fallback: string) => {
    const i = process.argv.indexOf(name);
    return i > -1 ? process.argv[i + 1] : fallback;
  };
  const host = arg('--host', '127.0.0.1');
  // 3100, not 3000: 3000 is the default for most JS dev servers and was
  // already taken on the dev Mac (failure 008).
  const port = arg('--port', '3100');

  const status = Object.fromEntries(
    execFileSync('supabase', ['status', '-o', 'env'], { encoding: 'utf8' })
      .split('\n')
      .map((line) => line.match(/^([A-Z_]+)="?(.*?)"?$/))
      .filter((m): m is RegExpMatchArray => m !== null)
      .map((m) => [m[1], m[2]]),
  );

  const apiUrl = status.API_URL;
  const anonKey = status.ANON_KEY;
  const serviceRoleKey = status.SERVICE_ROLE_KEY;
  if (!apiUrl || !anonKey || !serviceRoleKey) {
    console.error('Could not read `supabase status`. Is the local stack running (`supabase start`)?');
    process.exit(1);
  }

  // Signed upload URLs are built from SUPABASE_URL, so it must be reachable
  // from the device that uploads (the phone can't reach 127.0.0.1 on the Mac).
  const supabaseUrl = apiUrl.replace('127.0.0.1', host);

  writeFileSync(
    '.env',
    [
      '# Generated by `npm run local:setup` for the LOCAL Supabase stack. Not for production.',
      `PORT=${port}`,
      `SUPABASE_URL=${supabaseUrl}`,
      `SUPABASE_SERVICE_ROLE_KEY=${serviceRoleKey}`,
      `SUPABASE_ANON_KEY=${anonKey}`,
      'SUPABASE_STORAGE_BUCKET=evidence',
      '',
    ].join('\n'),
  );

  await ensureDemoUsers(apiUrl, serviceRoleKey);

  const xc = (url: string) => url.replace('://', ':/$()/');
  console.log(`Wrote .env (SUPABASE_URL=${supabaseUrl}) and created ${DEMO_USERS.length} demo users:`);
  for (const u of DEMO_USERS) console.log(`  ${u.role.padEnd(8)} ${u.email} / ${u.password}`);
  console.log('\nlablog-ios/Config/Secrets.xcconfig:\n');
  console.log(`LABLOG_API_BASE_URL = ${xc(`http://${host}:${port}/api`)}`);
  console.log(`SUPABASE_URL = ${xc(supabaseUrl)}`);
  console.log(`SUPABASE_ANON_KEY = ${anonKey}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
